#!/usr/bin/env python3
"""O34 bounded normalizer discovery.

This is a candidate generator, not a proof. It computes the equational congruence generated by a
small context on the complete bounded free-magma universe, then asks which small semantic observer
from a frozen grammar exactly classifies the bounded derivability classes.

The calibration contexts are deliberately mixed with negative controls. A newly surfaced observer
is only a hypothesis for a later Lean certificate.
"""

from __future__ import annotations

from dataclasses import dataclass
from itertools import product
from typing import Callable, Dict, Iterable, List, Sequence, Tuple, Union

Var = int
Term = Union[Var, Tuple["Term", "Term"]]

VARS: Tuple[Var, ...] = (0, 1, 2)
MAX_LEAVES = 4


def fork(a: Term, b: Term) -> Term:
    return (a, b)


def leaves(t: Term) -> int:
    if isinstance(t, int):
        return 1
    return leaves(t[0]) + leaves(t[1])


def word(t: Term) -> Tuple[Var, ...]:
    if isinstance(t, int):
        return (t,)
    return word(t[0]) + word(t[1])


def first(t: Term) -> Var:
    return word(t)[0]


def last(t: Term) -> Var:
    return word(t)[-1]


def is_leaf(t: Term) -> bool:
    return isinstance(t, int)


def term_key(t: Term):
    if isinstance(t, int):
        return (0, t)
    return (1, term_key(t[0]), term_key(t[1]))


def render(t: Term) -> str:
    if isinstance(t, int):
        return "xyz"[t]
    return f"({render(t[0])}*{render(t[1])})"


def generate_terms() -> Tuple[List[Term], Dict[int, List[Term]]]:
    by_size: Dict[int, List[Term]] = {1: list(VARS)}
    for n in range(2, MAX_LEAVES + 1):
        out = set()
        for k in range(1, n):
            for a in by_size[k]:
                for b in by_size[n - k]:
                    out.add(fork(a, b))
        by_size[n] = sorted(out, key=term_key)
    all_terms: List[Term] = []
    for n in range(1, MAX_LEAVES + 1):
        all_terms.extend(by_size[n])
    return all_terms, by_size


ALL_TERMS, TERMS_BY_SIZE = generate_terms()
TERM_INDEX = {t: i for i, t in enumerate(ALL_TERMS)}


@dataclass(frozen=True)
class Law:
    lhs: Term
    rhs: Term
    vars_used: Tuple[Var, ...]


@dataclass(frozen=True)
class Context:
    name: str
    laws: Tuple[Law, ...]


def subst(t: Term, env: Dict[Var, Term]) -> Term:
    if isinstance(t, int):
        return env[t]
    return fork(subst(t[0], env), subst(t[1], env))


def bounded_substitutions(vars_used: Sequence[Var]) -> Iterable[Dict[Var, Term]]:
    """Enumerate only substitutions whose distinct-variable leaf-size lower bound fits.

    Enumerating ALL_TERMS^k and filtering afterwards is precisely the kind of waste the flywheel is
    meant to remove. Size compositions are tiny here; only then do we form concrete products.
    Repeated-variable laws may still be rejected after instantiation, which is safe.
    """
    k = len(vars_used)
    for sizes in product(range(1, MAX_LEAVES + 1), repeat=k):
        if sum(sizes) > MAX_LEAVES:
            continue
        pools = [TERMS_BY_SIZE[s] for s in sizes]
        for values in product(*pools):
            yield dict(zip(vars_used, values))


class DSU:
    def __init__(self, n: int):
        self.p = list(range(n))
        self.rank = [0] * n

    def find(self, a: int) -> int:
        while self.p[a] != a:
            self.p[a] = self.p[self.p[a]]
            a = self.p[a]
        return a

    def union(self, a: int, b: int) -> bool:
        a, b = self.find(a), self.find(b)
        if a == b:
            return False
        if self.rank[a] < self.rank[b]:
            a, b = b, a
        self.p[b] = a
        if self.rank[a] == self.rank[b]:
            self.rank[a] += 1
        return True


def congruence_for(ctx: Context) -> DSU:
    dsu = DSU(len(ALL_TERMS))

    for law in ctx.laws:
        for env in bounded_substitutions(law.vars_used):
            l = subst(law.lhs, env)
            r = subst(law.rhs, env)
            if leaves(l) <= MAX_LEAVES and leaves(r) <= MAX_LEAVES:
                il = TERM_INDEX.get(l)
                ir = TERM_INDEX.get(r)
                if il is not None and ir is not None:
                    dsu.union(il, ir)

    # Least operation congruence inside the frozen bounded universe.
    changed = True
    while changed:
        changed = False
        representatives: Dict[Tuple[int, int], int] = {}
        for i, t in enumerate(ALL_TERMS):
            if isinstance(t, int):
                continue
            key = (dsu.find(TERM_INDEX[t[0]]), dsu.find(TERM_INDEX[t[1]]))
            if key in representatives:
                changed |= dsu.union(i, representatives[key])
            else:
                representatives[key] = i
    return dsu


Observer = Callable[[Term], object]
OBSERVERS: Tuple[Tuple[str, Observer, int], ...] = (
    ("first", lambda t: first(t), 1),
    ("last", lambda t: last(t), 1),
    ("first_last", lambda t: (first(t), last(t)), 2),
    ("leaf_first_last", lambda t: (is_leaf(t), first(t), last(t)), 3),
    ("word", lambda t: word(t), 4),
)


def observer_report(dsu: DSU, obs: Observer):
    class_to_sig: Dict[int, object] = {}
    sig_to_class: Dict[object, int] = {}
    sound = True
    complete = True
    sound_witness = None
    complete_witness = None

    for i, t in enumerate(ALL_TERMS):
        c = dsu.find(i)
        s = obs(t)
        old_s = class_to_sig.get(c)
        if old_s is None:
            class_to_sig[c] = s
        elif old_s != s and sound:
            sound = False
            for j, u in enumerate(ALL_TERMS):
                if dsu.find(j) == c and obs(u) == old_s:
                    sound_witness = (u, t)
                    break
        old_c = sig_to_class.get(s)
        if old_c is None:
            sig_to_class[s] = c
        elif old_c != c and complete:
            complete = False
            for j, u in enumerate(ALL_TERMS):
                if dsu.find(j) == old_c and obs(u) == s:
                    complete_witness = (u, t)
                    break

    return sound, complete, sound_witness, complete_witness


def classes(dsu: DSU) -> int:
    return len({dsu.find(i) for i in range(len(ALL_TERMS))})


x, y, z = 0, 1, 2
CONTEXTS = (
    Context("left_projection", (Law(fork(x, y), x, (x, y)),)),
    Context("right_projection", (Law(fork(x, y), y, (x, y)),)),
    Context(
        "associativity",
        (Law(fork(fork(x, y), z), fork(x, fork(y, z)), (x, y, z)),),
    ),
    Context(
        "rectangular_two_axiom",
        (
            Law(fork(fork(x, y), z), fork(x, z), (x, y, z)),
            Law(fork(x, fork(y, z)), fork(x, z), (x, y, z)),
        ),
    ),
    Context("idempotence", (Law(fork(x, x), x, (x,)),)),
    Context("commutativity", (Law(fork(x, y), fork(y, x), (x, y)),)),
)

EXPECTED_MINIMAL = {
    "left_projection": "first",
    "right_projection": "last",
    "associativity": "word",
    "rectangular_two_axiom": "leaf_first_last",
    "idempotence": None,
    "commutativity": None,
}


def main() -> None:
    print("O34 BOUNDED NORMALIZER DISCOVERY")
    print(f"variables={VARS} max_leaves={MAX_LEAVES} terms={len(ALL_TERMS)}")
    print("observer_grammar=" + ",".join(name for name, _, _ in OBSERVERS))
    print()

    discovered: Dict[str, str | None] = {}
    for ctx in CONTEXTS:
        dsu = congruence_for(ctx)
        exact: List[Tuple[int, str]] = []
        print(f"CONTEXT {ctx.name} classes={classes(dsu)}")
        for name, obs, cost in OBSERVERS:
            sound, complete, sw, cw = observer_report(dsu, obs)
            if sound and complete:
                exact.append((cost, name))
            witness = ""
            if not sound and sw:
                witness += f" sound_ce={render(sw[0])}~{render(sw[1])}"
            if not complete and cw:
                witness += f" complete_ce={render(cw[0])}!~{render(cw[1])}"
            print(
                f"  {name:16s} sound={str(sound):5s} complete={str(complete):5s}"
                f" exact={str(sound and complete):5s}{witness}"
            )
        exact.sort()
        winner = exact[0][1] if exact else None
        discovered[ctx.name] = winner
        print(f"  WINNER {winner}")
        print()

    print("DISCOVERY_SUMMARY")
    for name, winner in discovered.items():
        print(f"  {name}: {winner}")

    failures = []
    for name, expected in EXPECTED_MINIMAL.items():
        if discovered.get(name) != expected:
            failures.append((name, expected, discovered.get(name)))
    if failures:
        print("\nO34_VERDICT=FAIL")
        for name, expected, got in failures:
            print(f"  mismatch {name}: expected={expected} got={got}")
        raise SystemExit(1)

    print("\nO34_VERDICT=PASS")
    print("NEW_CANDIDATE=rectangular_two_axiom:leaf_first_last")
    print("NEGATIVE_CONTROLS=idempotence,commutativity:no_exact_observer_in_frozen_grammar")


if __name__ == "__main__":
    main()
